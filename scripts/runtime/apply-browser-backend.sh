#!/usr/bin/env bash
# Apply WEZDECK_BROWSER_BACKEND (cdp|ego) to host skill discovery and OpenClaw
# mcp.servers. Single write entry for browser capability — do not hand-edit
# OpenClaw chrome-devtools / ego skill links after this script owns them.
#
# Usage:
#   apply-browser-backend.sh                 # apply current env/config
#   apply-browser-backend.sh --set ego|cdp   # write shell-env.d then apply
#   apply-browser-backend.sh --dry-run
#   apply-browser-backend.sh --skip-probe    # skip CDP/Ego liveness checks
#   apply-browser-backend.sh --skip-reload   # skip openclaw mcp reload
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPO_ROOT="$(cd "${WEZDECK_REPO:-$REPO_ROOT}" && pwd -P)"

# shellcheck disable=SC1091
source "$SCRIPT_DIR/ego-browser-lib.sh"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/browser-agent-status-lib.sh"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/runtime-env-lib.sh" 2>/dev/null || true
# shellcheck disable=SC1091
source "$SCRIPT_DIR/runtime-log-lib.sh" 2>/dev/null || true
# shellcheck disable=SC1091
source "$SCRIPT_DIR/windows-runtime-paths-lib.sh" 2>/dev/null || true

WEZTERM_RUNTIME_LOG_SOURCE="${WEZTERM_RUNTIME_LOG_SOURCE:-apply-browser-backend}"

dry_run=0
skip_probe=0
skip_reload=0
set_backend=""

usage() {
  sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

while (($#)); do
  case "$1" in
    --dry-run) dry_run=1; shift ;;
    --skip-probe) skip_probe=1; shift ;;
    --skip-reload) skip_reload=1; shift ;;
    --set)
      set_backend="${2:-}"
      shift 2
      ;;
    -h|--help) usage; exit 0 ;;
    *)
      printf 'apply-browser-backend: unknown arg: %s\n' "$1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if declare -F runtime_env_load_managed >/dev/null 2>&1; then
  runtime_env_load_managed || true
fi

SHELL_ENV_DIR="${SHELL_ENV_DIR:-$HOME/.config/shell-env.d}"
ENV_FILE="$SHELL_ENV_DIR/wezdeck-browser-agent.env"
CDP_PORT="${WEZDECK_CDP_PORT:-9222}"
CDP_MCP_VERSION="${WEZDECK_CHROME_DEVTOOLS_MCP_VERSION:-1.9.0}"

write_env_file() {
  local backend="$1"
  mkdir -p "$SHELL_ENV_DIR"
  chmod 700 "$SHELL_ENV_DIR" 2>/dev/null || true
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<EOF
# Generated by scripts/runtime/apply-browser-backend.sh — do not hand-conflict.
# Mode 600. Loaded via runtime_env_load_managed / interactive shell-env.d.
export WEZDECK_BROWSER_BACKEND=$backend
EOF
  chmod 600 "$tmp"
  if ((dry_run)); then
    printf 'dry-run: would write %s → WEZDECK_BROWSER_BACKEND=%s\n' "$ENV_FILE" "$backend"
    rm -f "$tmp"
  else
    mv -f "$tmp" "$ENV_FILE"
    printf 'wrote %s (WEZDECK_BROWSER_BACKEND=%s)\n' "$ENV_FILE" "$backend"
  fi
}

pending_set=""
if [[ -n "$set_backend" ]]; then
  case "$set_backend" in
    cdp|ego) pending_set="$set_backend" ;;
    *)
      printf 'apply-browser-backend: --set requires cdp or ego, got %q\n' "$set_backend" >&2
      exit 2
      ;;
  esac
fi

backend="${pending_set:-${WEZDECK_BROWSER_BACKEND:-}}"
if [[ -z "$backend" && -f "$ENV_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  backend="${WEZDECK_BROWSER_BACKEND:-}"
fi

if [[ -z "$backend" ]]; then
  printf 'apply-browser-backend: WEZDECK_BROWSER_BACKEND unset. Run with --set ego|cdp first.\n' >&2
  exit 2
fi

case "$backend" in
  cdp|ego) ;;
  *)
    printf 'apply-browser-backend: invalid backend %q (want cdp|ego)\n' "$backend" >&2
    exit 2
    ;;
esac

printf 'apply-browser-backend: backend=%s dry_run=%s\n' "$backend" "$dry_run"

probe_cdp() {
  curl -sS -m 3 "http://127.0.0.1:${CDP_PORT}/json/version" >/dev/null 2>&1
}

probe_ego() {
  local wrapper="$REPO_ROOT/scripts/runtime/cli/ego-browser"
  if [[ ! -x "$wrapper" ]]; then
    return 1
  fi
  # ego-browser.exe often prints console.log on stderr when launched from WSL.
  "$wrapper" nodejs -e "console.log('ego-browser ready')" 2>&1 \
    | grep -q 'ego-browser ready'
}

# Probe before writing env / MCP so a failed probe leaves no half-applied state.
if ((skip_probe == 0)); then
  if [[ "$backend" == "cdp" ]]; then
    if ! probe_cdp; then
      printf 'apply-browser-backend: CDP http://127.0.0.1:%s/json/version not answering.\n' "$CDP_PORT" >&2
      printf '  Fix: ensure WezDeck debug Chrome auto-start / Alt+b (docs/browser-debug.md).\n' >&2
      printf '  Or re-run with --skip-probe after you accept writing MCP anyway.\n' >&2
      exit 1
    fi
    printf 'probe: CDP :%s ok\n' "$CDP_PORT"
  else
    if ! probe_ego; then
      printf 'apply-browser-backend: ego-browser probe failed.\n' >&2
      printf '  Fix: open ego (lite) on Windows, confirm ego-browser.exe, ensure WSL wrapper works:\n' >&2
      printf '    %s/scripts/runtime/cli/ego-browser nodejs -e \"console.log('\''ego-browser ready'\'')\"\n' "$REPO_ROOT" >&2
      printf '  Or re-run with --skip-probe.\n' >&2
      exit 1
    fi
    printf 'probe: ego-browser ok\n'
  fi
fi

if [[ -n "$pending_set" ]]; then
  write_env_file "$pending_set"
  export WEZDECK_BROWSER_BACKEND="$pending_set"
fi

link_skill() {
  local src=$1 dst=$2
  if [[ ! -e "$src" && ! -L "$src" ]]; then
    printf '  skip link (missing source): %s\n' "$src"
    return 1
  fi
  if ((dry_run)); then
    printf '  dry-run link %s → %s\n' "$dst" "$src"
    return 0
  fi
  mkdir -p "$(dirname "$dst")"
  if [[ -L "$dst" || -e "$dst" ]]; then
    local cur
    cur="$(readlink -f "$dst" 2>/dev/null || true)"
    local want
    want="$(readlink -f "$src" 2>/dev/null || printf '%s' "$src")"
    if [[ "$cur" == "$want" ]]; then
      printf '  ok %s\n' "$dst"
      return 0
    fi
    rm -rf "$dst"
  fi
  ln -s "$src" "$dst"
  printf '  linked %s → %s\n' "$dst" "$src"
}

# --- skill discovery ---
# Install ego-window.ps1 into the Windows runtime home so WezTerm Lua Alt+b
# can invoke it without a \\wsl$ path.
install_ego_window_script() {
  if ! windows_runtime_detect_paths 2>/dev/null; then
    printf '  warn: cannot resolve Windows runtime home; skip ego-window.ps1 install\n'
    return 0
  fi
  # Canonical copy ships inside wezterm-x/scripts/ so sync-runtime --live
  # keeps it; scripts/runtime/ego-window.ps1 is the same file for WSL callers.
  local src="$REPO_ROOT/wezterm-x/scripts/ego-window.ps1"
  if [[ ! -f "$src" ]]; then
    src="$REPO_ROOT/scripts/runtime/ego-window.ps1"
  fi
  local dst="$WINDOWS_RUNTIME_HOME_WSL/scripts/ego-window.ps1"
  if [[ ! -f "$src" ]]; then
    printf '  warn: missing ego-window.ps1 in wezterm-x/scripts or scripts/runtime\n'
    return 0
  fi
  if ((dry_run)); then
    printf '  dry-run: install %s → %s\n' "$src" "$dst"
    return 0
  fi
  mkdir -p "$(dirname "$dst")"
  # sync-runtime already mirrors wezterm-x/scripts; still copy for machines
  # that have not synced yet after apply.
  cp -f "$src" "$dst"
  printf '  installed %s\n' "$dst"
}

printf 'windows helpers:\n'
install_ego_window_script

printf 'browser-agent status:\n'
if ((dry_run)); then
  printf '  dry-run: write status.json backend=%s\n' "$backend"
else
  if [[ "$backend" == "ego" ]]; then
    browser_agent_status_write --backend ego --probe-ego >/dev/null
  else
    browser_agent_status_write --backend cdp --probe-ego >/dev/null
  fi
  printf '  wrote %s\n' "$(browser_agent_status_file 2>/dev/null || echo status.json)"
fi

printf 'skills:\n'
vendor_ego=""
vendor_ego="$(ego_browser_vendor_skill_dir 2>/dev/null || true)"
if [[ -n "$vendor_ego" ]]; then
  link_skill "$vendor_ego" "$HOME/.agents/skills/ego-browser" || true
  if [[ -d "$HOME/.claude/skills" || -L "$HOME/.claude/skills" ]]; then
    link_skill "$vendor_ego" "$HOME/.claude/skills/ego-browser" || true
  fi
  link_skill "$vendor_ego" "$REPO_ROOT/openclaw/workspace/skills/ego-browser" || true
else
  printf '  warn: vendor ego-browser skill not found under Windows .agents/skills\n'
fi

# browser-agent platform skill (if present in checkout)
if [[ -d "$REPO_ROOT/skills/browser-agent" ]]; then
  if [[ -x "$REPO_ROOT/scripts/dev/link-platform-skills.sh" ]]; then
    if ((dry_run)); then
      printf '  dry-run: link-platform-skills.sh (browser-agent row)\n'
    else
      # Full manifest link is fine and keeps other platform skills consistent.
      "$REPO_ROOT/scripts/dev/link-platform-skills.sh" >/dev/null || \
        "$REPO_ROOT/scripts/dev/link-platform-skills.sh"
    fi
  fi
fi

# --- OpenClaw MCP ---
if ! command -v openclaw >/dev/null 2>&1; then
  printf 'openclaw: CLI not on PATH — skipped mcp.servers write\n'
  if declare -F runtime_log_warn >/dev/null 2>&1; then
    runtime_log_warn browser_agent "openclaw missing; mcp skipped" backend="$backend"
  fi
else
  printf 'openclaw mcp:\n'
  if [[ "$backend" == "cdp" ]]; then
    if ((dry_run)); then
      printf '  dry-run: openclaw mcp add chrome-devtools (pinned %s)\n' "$CDP_MCP_VERSION"
    else
      # Idempotent: unset then add so args stay exact.
      openclaw mcp unset chrome-devtools >/dev/null 2>&1 || true
      if ! command -v chrome-devtools-mcp >/dev/null 2>&1; then
        printf '  installing chrome-devtools-mcp@%s globally…\n' "$CDP_MCP_VERSION"
        npm i -g "chrome-devtools-mcp@${CDP_MCP_VERSION}"
      fi
      openclaw mcp add chrome-devtools \
        --command chrome-devtools-mcp \
        --arg --browser-url="http://127.0.0.1:${CDP_PORT}" \
        --arg --usageStatistics=false \
        --timeout 90 \
        --connect-timeout 60 \
        --no-probe
      printf '  chrome-devtools MCP written\n'
      if ((skip_reload == 0)); then
        openclaw mcp reload || true
        printf '  mcp reload requested\n'
      fi
    fi
  else
    if ((dry_run)); then
      printf '  dry-run: openclaw mcp unset chrome-devtools\n'
    else
      if openclaw mcp list 2>/dev/null | grep -q 'chrome-devtools'; then
        openclaw mcp unset chrome-devtools
        printf '  chrome-devtools MCP removed\n'
      else
        printf '  chrome-devtools MCP already absent\n'
      fi
      if ((skip_reload == 0)); then
        openclaw mcp reload || true
        printf '  mcp reload requested\n'
      fi
    fi
  fi
fi

if declare -F runtime_log_info >/dev/null 2>&1; then
  runtime_log_info browser_agent "browser backend applied" \
    backend="$backend" dry_run="$dry_run"
fi

printf 'done: backend=%s\n' "$backend"
printf 'Agents: export WEZDECK_BROWSER_BACKEND=%s (or rely on %s)\n' \
  "$backend" "$ENV_FILE"
